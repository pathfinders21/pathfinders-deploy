import React, { useCallback, useEffect, useMemo, useState } from 'react';
import {
  AlertTriangle,
  Calendar,
  Check,
  ChevronRight,
  Clock,
  Loader2,
  Plus,
  RefreshCw,
  Sparkles,
  Trash2,
  Flag,
} from 'lucide-react';
import {
  ApiError,
  api,
  type PlanMilestone,
  type RoadmapPlan,
  type RoadmapView,
  type RoadmapStep,
} from '../lib/api.ts';
import { signInHref, type Session } from '../lib/session.ts';

/**
 * The roadmap, generated from the student's own goal and weekly hours.
 *
 * Three things this screen refuses to do. It never shows a plan as if it were already
 * saved: generation returns a proposal and saving is a second, explicit call. It never
 * marks a step complete on the student's behalf: the only writer of a `done` status is
 * the person pressing the checkbox. And it never hides where a plan came from, so every
 * generated plan carries the engine that produced it.
 */

interface Props {
  session: Session;
  onOpenAgent?: () => void;
}

const err = (e: unknown, fallback: string) =>
  e instanceof ApiError ? e : new ApiError({ kind: 'server', status: 0, message: fallback });

function EngineChip({ engine }: { engine: 'gemini' | 'demo' }) {
  return (
    <span
      className={`text-[10px] px-2 py-0.5 rounded-full border ${
        engine === 'gemini'
          ? 'bg-emerald-500/10 text-emerald-300 border-emerald-500/20'
          : 'bg-amber-500/10 text-amber-200 border-amber-500/20'
      }`}
    >
      {engine === 'gemini' ? 'Generated by the model' : 'Demo engine: no provider key configured'}
    </span>
  );
}

function ErrorNote({ error, onRetry }: { error: ApiError; onRetry?: () => void }) {
  return (
    <div className="p-5 rounded-2xl bg-rose-950/40 border border-rose-500/30 text-rose-100 text-sm space-y-3">
      <div className="flex items-center gap-2 font-medium">
        <AlertTriangle className="w-4 h-4" />
        <span>That did not work</span>
      </div>
      <p className="text-xs text-rose-100/80">{error.userMessage}</p>
      <div className="flex items-center gap-3">
        {onRetry && error.retryable && (
          <button
            type="button"
            onClick={onRetry}
            className="text-xs px-3 py-1.5 rounded-full bg-white/10 hover:bg-white/20"
          >
            Try again
          </button>
        )}
        <span className="text-[11px] text-rose-100/60">Nothing was changed. No plan was saved.</span>
      </div>
    </div>
  );
}

/** The unsaved plan, editable in place before it is applied. */
function PlanPreview({
  plan,
  engine,
  busy,
  onChange,
  onAccept,
  onReject,
  onRegenerate,
}: {
  plan: RoadmapPlan;
  engine: 'gemini' | 'demo';
  busy: boolean;
  onChange: (plan: RoadmapPlan) => void;
  onAccept: () => void;
  onReject: () => void;
  onRegenerate: () => void;
}) {
  const renameMilestone = (index: number, title: string) => {
    const milestones = plan.milestones.map((m, i) => (i === index ? { ...m, title } : m));
    onChange({ ...plan, milestones });
  };
  const dropMilestone = (index: number) =>
    onChange({ ...plan, milestones: plan.milestones.filter((_, i) => i !== index) });

  return (
    <div className="p-6 rounded-2xl bg-white/[0.02] border border-white/10 space-y-5">
      <div className="flex flex-wrap items-center gap-2">
        <span className="text-[10px] px-2 py-0.5 rounded border bg-white/5 text-white/70 border-white/15">
          Proposal, not saved
        </span>
        <EngineChip engine={engine} />
        <span className="text-[10px] text-white/40 ml-auto">
          {plan.milestones.length} milestones ·{' '}
          {plan.milestones.reduce((n, m) => n + m.tasks.length, 0)} tasks
        </span>
      </div>

      <div>
        <h3 style={{ fontFamily: "'Instrument Serif', serif" }} className="text-2xl text-white">
          {plan.title}
        </h3>
        <p className="text-sm text-white/70 mt-2 leading-relaxed">{plan.rationale}</p>
      </div>

      <ol className="space-y-4">
        {plan.milestones.map((milestone, index) => (
          <li key={`${milestone.title}-${index}`} className="p-4 rounded-xl bg-white/[0.02] border border-white/10 space-y-3">
            <div className="flex items-center gap-2">
              <span className="text-[10px] w-6 h-6 shrink-0 grid place-items-center rounded-full bg-white/5 border border-white/15 text-white/60">
                {index + 1}
              </span>
              <input
                aria-label={`Milestone ${index + 1} title`}
                value={milestone.title}
                onChange={(e) => renameMilestone(index, e.target.value)}
                className="flex-1 px-3 py-1.5 rounded-lg bg-white/5 border border-white/10 text-sm text-white focus:outline-none focus:border-white/40"
              />
              <button
                type="button"
                onClick={() => dropMilestone(index)}
                aria-label={`Remove milestone ${index + 1} before saving`}
                className="p-1.5 rounded-lg text-white/40 hover:text-rose-300 hover:bg-white/5"
              >
                <Trash2 className="w-3.5 h-3.5" />
              </button>
            </div>
            <p className="text-xs text-white/60 leading-relaxed">
              <span className="text-white/40 uppercase tracking-wider text-[10px] mr-2">Why this matters</span>
              {milestone.why}
            </p>
            <ul className="space-y-1.5">
              {milestone.tasks.map((task) => (
                <li key={task.title} className="text-xs text-white/70 flex items-start gap-2">
                  <ChevronRight className="w-3 h-3 mt-0.5 shrink-0 text-white/30" />
                  <span>
                    {task.title}
                    {task.estimate && <span className="text-white/40"> · {task.estimate}</span>}
                    {task.detail && <span className="block text-white/45 mt-0.5">{task.detail}</span>}
                  </span>
                </li>
              ))}
            </ul>
          </li>
        ))}
      </ol>

      <p className="text-[11px] text-white/45">
        Editing here changes the proposal only. Nothing is written to your roadmap until you save it, and
        generated steps start as not started.
      </p>

      <div className="flex flex-wrap items-center gap-2">
        <button
          type="button"
          disabled={busy || plan.milestones.length === 0}
          onClick={onAccept}
          className="px-4 py-2 rounded-xl bg-emerald-500/20 hover:bg-emerald-500/30 text-emerald-200 border border-emerald-500/30 text-xs font-medium inline-flex items-center gap-1.5 disabled:opacity-40"
        >
          {busy ? <Loader2 className="w-3.5 h-3.5 animate-spin" /> : <Check className="w-3.5 h-3.5" />}
          <span>Save this plan to my roadmap</span>
        </button>
        <button
          type="button"
          disabled={busy}
          onClick={onRegenerate}
          className="px-3.5 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/15 text-white/80 text-xs inline-flex items-center gap-1.5 disabled:opacity-40"
        >
          <RefreshCw className="w-3.5 h-3.5" />
          <span>Regenerate</span>
        </button>
        <button
          type="button"
          disabled={busy}
          onClick={onReject}
          className="px-3.5 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/10 text-white/60 hover:text-white text-xs disabled:opacity-40"
        >
          Discard
        </button>
      </div>
    </div>
  );
}

function StepRow({
  step,
  busy,
  onToggle,
  onDelete,
}: {
  step: RoadmapStep;
  busy: boolean;
  onToggle: (step: RoadmapStep) => void;
  onDelete: (step: RoadmapStep) => void;
}) {
  const overdue = step.status === 'pending' && step.deadline ? new Date(step.deadline).getTime() < Date.now() : false;
  return (
    <li className="flex items-start gap-3 p-3 rounded-xl bg-white/[0.02] border border-white/10">
      <button
        type="button"
        disabled={busy}
        onClick={() => onToggle(step)}
        aria-label={step.status === 'done' ? `Mark ${step.title} as not done` : `Mark ${step.title} as done`}
        className={`mt-0.5 w-4 h-4 shrink-0 rounded border grid place-items-center disabled:opacity-40 ${
          step.status === 'done' ? 'bg-emerald-500/60 border-emerald-400/60' : 'border-white/25 hover:border-white/60'
        }`}
      >
        {step.status === 'done' && <Check className="w-3 h-3 text-white" />}
      </button>
      <div className="min-w-0 flex-1">
        <div className="flex flex-wrap items-center gap-2">
          <span className={`text-sm ${step.status === 'done' ? 'text-white/45 line-through' : 'text-white/85'}`}>
            {step.title}
          </span>
          {step.origin === 'user' && (
            <span className="text-[10px] px-1.5 py-0.5 rounded bg-white/5 border border-white/10 text-white/50">yours</span>
          )}
          {step.estimate && <span className="text-[11px] text-white/40">{step.estimate}</span>}
          {step.deadline && (
            <span className={`text-[11px] inline-flex items-center gap-1 ${overdue ? 'text-amber-300' : 'text-white/40'}`}>
              <Calendar className="w-3 h-3" />
              {new Date(step.deadline).toLocaleDateString()}
              {overdue && ' · overdue'}
            </span>
          )}
        </div>
        {step.detail && <p className="text-xs text-white/55 mt-1 leading-relaxed">{step.detail}</p>}
      </div>
      {step.origin === 'user' && (
        <button
          type="button"
          disabled={busy}
          onClick={() => onDelete(step)}
          aria-label={`Delete ${step.title}`}
          className="p-1.5 rounded-lg text-white/35 hover:text-rose-300 hover:bg-white/5 disabled:opacity-40"
        >
          <Trash2 className="w-3.5 h-3.5" />
        </button>
      )}
    </li>
  );
}

export const RoadmapWorkspace: React.FC<Props> = ({ session, onOpenAgent }) => {
  const ready = session.status === 'ready';
  const [view, setView] = useState<RoadmapView | null>(null);
  const [plan, setPlan] = useState<{ plan: RoadmapPlan; engine: 'gemini' | 'demo' } | null>(null);
  const [loading, setLoading] = useState(false);
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState<ApiError | null>(null);
  const [notice, setNotice] = useState<string | null>(null);
  const [goalTitle, setGoalTitle] = useState('');
  const [newStep, setNewStep] = useState('');
  const [deadline, setDeadline] = useState('');
  const [openFor, setOpenFor] = useState<string | null>(null);

  const load = useCallback(async () => {
    if (!ready) return;
    setLoading(true);
    setError(null);
    try {
      setView(await api.roadmap());
    } catch (e) {
      setError(err(e, 'Could not load your roadmap.'));
    } finally {
      setLoading(false);
    }
  }, [ready]);

  useEffect(() => {
    void load();
  }, [load]);

  const goals = useMemo(() => view?.goals ?? [], [view]);
  const roadmap = view?.roadmap ?? null;

  const createGoal = async () => {
    if (goalTitle.trim().length < 3) return;
    setBusy(true);
    setError(null);
    try {
      await api.createGoal({ title: goalTitle.trim(), source: 'user' });
      setGoalTitle('');
      setNotice('Goal saved. Generate a roadmap for it when you are ready.');
      await load();
    } catch (e) {
      setError(err(e, 'That goal could not be saved.'));
    } finally {
      setBusy(false);
    }
  };

  const generate = async (regenerate = false) => {
    setBusy(true);
    setError(null);
    setNotice(null);
    try {
      const result = await api.planRoadmap({ regenerate });
      setPlan({ plan: result.plan, engine: result.engine });
    } catch (e) {
      setError(err(e, 'No plan was generated.'));
    } finally {
      setBusy(false);
    }
  };

  const apply = async () => {
    if (!plan) return;
    setBusy(true);
    setError(null);
    try {
      const result = await api.applyPlan({ plan: plan.plan });
      setView(result);
      setPlan(null);
      setNotice(
        `Saved: ${result.created} new step${result.created === 1 ? '' : 's'}${
          result.replaced ? `, ${result.replaced} replaced` : ''
        }. Every new step starts as not done.`,
      );
    } catch (e) {
      // A rejected plan is shown whole: the server validates before writing anything.
      setError(err(e, 'That plan was not accepted, so nothing was saved.'));
    } finally {
      setBusy(false);
    }
  };

  const toggleStep = async (step: RoadmapStep) => {
    setBusy(true);
    setError(null);
    try {
      setView(await api.updateStep(step.id, { status: step.status === 'done' ? 'pending' : 'done' }));
    } catch (e) {
      setError(err(e, 'That step could not be updated.'));
    } finally {
      setBusy(false);
    }
  };

  const deleteStep = async (step: RoadmapStep) => {
    setBusy(true);
    setError(null);
    try {
      setView(await api.deleteStep(step.id));
    } catch (e) {
      setError(err(e, 'That step could not be removed.'));
    } finally {
      setBusy(false);
    }
  };

  const addStep = async (parentId?: string) => {
    if (newStep.trim().length < 3) return;
    setBusy(true);
    setError(null);
    try {
      const result = await api.addStep({
        title: newStep.trim(),
        parentId,
        deadline: deadline || undefined,
      });
      setView(result);
      setNewStep('');
      setDeadline('');
      setOpenFor(null);
    } catch (e) {
      setError(err(e, 'That step could not be added.'));
    } finally {
      setBusy(false);
    }
  };

  if (session.status === 'signed_out') {
    return (
      <Shell>
        <div className="p-6 rounded-2xl bg-white/[0.02] border border-white/10 space-y-4 max-w-xl">
          <h2 className="text-lg font-medium text-white">Sign in to build a roadmap</h2>
          <p className="text-sm text-white/60">
            Roadmaps are generated for a goal and saved against your account, so this screen needs a session.
            The roadmap below the sign in link is a static preview.
          </p>
          <a
            href={signInHref('#/roadmaps')}
            className="liquid-glass rounded-full px-6 py-3 text-sm font-medium text-white inline-block hover:scale-[1.02] transition-transform"
          >
            Sign in to continue
          </a>
        </div>
      </Shell>
    );
  }

  const milestones = roadmap?.steps.filter((s) => s.kind === 'milestone') ?? [];
  const tasksOf = (id: string) => roadmap?.steps.filter((s) => s.parentId === id) ?? [];

  return (
    <Shell>
      <div className="flex flex-col md:flex-row md:items-end justify-between gap-4 pb-6 border-b border-white/10">
        <div>
          <div className="flex items-center gap-2 text-xs text-white/50 mb-2">
            <Sparkles className="w-3.5 h-3.5" />
            <span>Roadmap</span>
          </div>
          <h2 style={{ fontFamily: "'Instrument Serif', serif" }} className="text-3xl sm:text-4xl text-white font-normal">
            A plan for your goal, at your hours
          </h2>
          <p className="text-white/60 text-sm mt-2 max-w-2xl">
            Built from the goal stored on your profile and the weekly hours you entered, ordered into phases with
            estimates. You approve the plan before anything is saved.
          </p>
        </div>
        <button
          type="button"
          disabled={busy || !ready || goals.length === 0}
          onClick={() => void generate(Boolean(roadmap))}
          className="liquid-glass rounded-full px-5 py-2.5 text-sm font-medium text-white disabled:opacity-40 inline-flex items-center gap-2 shrink-0"
        >
          {busy ? <Loader2 className="w-4 h-4 animate-spin" /> : <RefreshCw className="w-4 h-4" />}
          <span>{roadmap ? 'Regenerate a plan' : 'Generate a roadmap'}</span>
        </button>
      </div>

      {error && (
        <div className="mt-6">
          <ErrorNote error={error} onRetry={() => void load()} />
        </div>
      )}
      {notice && (
        <div className="mt-6 p-4 rounded-2xl bg-emerald-950/30 border border-emerald-500/25 text-emerald-100 text-xs flex items-start gap-2">
          <Check className="w-4 h-4 shrink-0 mt-0.5" />
          <span>{notice}</span>
        </div>
      )}

      {!view && loading && (
        <div className="mt-8 p-5 rounded-2xl bg-white/[0.02] border border-white/10 flex items-center gap-3 text-sm text-white/60">
          <Loader2 className="w-4 h-4 animate-spin" />
          <span>Reading your goal and roadmap...</span>
        </div>
      )}

      {view && !view.goal && (
        <div className="mt-8 p-6 rounded-2xl bg-white/[0.02] border border-white/10 space-y-4 max-w-2xl">
          <h3 className="text-base text-white">Start with a goal</h3>
          <p className="text-sm text-white/60">
            A roadmap is generated for one goal. State it in your own words; you can change the goal later without
            losing your roadmap history.
          </p>
          <input
            aria-label="Your goal"
            value={goalTitle}
            onChange={(e) => setGoalTitle(e.target.value)}
            placeholder="e.g. Move into a backend engineering role within a year"
            className="w-full px-4 py-3 rounded-xl bg-white/5 border border-white/15 text-sm text-white placeholder:text-white/35 focus:outline-none focus:border-white/40"
          />
          <button
            type="button"
            disabled={busy || goalTitle.trim().length < 3}
            onClick={() => void createGoal()}
            className="px-4 py-2 rounded-xl bg-white/10 hover:bg-white/20 border border-white/20 text-white text-xs font-medium disabled:opacity-40"
          >
            Save this goal
          </button>
        </div>
      )}

      {plan && (
        <div className="mt-6">
          <PlanPreview
            plan={plan.plan}
            engine={plan.engine}
            busy={busy}
            onChange={(next) => setPlan({ ...plan, plan: next })}
            onAccept={() => void apply()}
            onReject={() => {
              setPlan(null);
              setNotice('Discarded. Nothing was saved, so your roadmap is exactly as it was.');
            }}
            onRegenerate={() => void generate(true)}
          />
        </div>
      )}

      {view?.goal && (
        <div className="mt-6 p-5 rounded-2xl bg-white/[0.02] border border-white/10">
          <div className="text-xs uppercase tracking-wider text-white/45">Your goal</div>
          <div className="flex flex-wrap items-center gap-3 mt-1">
            <span className="text-lg text-white">{view.goal.title}</span>
            <span className="text-[10px] px-2 py-0.5 rounded-full border bg-white/5 border-white/15 text-white/60">
              {view.goal.status}
            </span>
            {view.goal.source === 'ai' && (
              <span className="text-[10px] px-2 py-0.5 rounded-full border bg-white/5 border-white/15 text-white/50">
                suggested by the model, chosen by you
              </span>
            )}
          </div>
          {view.goal.rationale && <p className="text-xs text-white/55 mt-2">{view.goal.rationale}</p>}
        </div>
      )}

      {roadmap && (
        <div className="mt-8 space-y-6">
          <div className="flex flex-wrap items-center gap-3">
            <h3 style={{ fontFamily: "'Instrument Serif', serif" }} className="text-2xl text-white">
              {roadmap.title}
            </h3>
            <span className="text-[10px] text-white/40">
              revision {roadmap.revision} · {`${roadmap.stats.done}/${roadmap.stats.total}`} steps done
            </span>
          </div>
          {roadmap.rationale && <p className="text-sm text-white/60 max-w-3xl">{roadmap.rationale}</p>}

          <div className="grid grid-cols-2 sm:grid-cols-4 gap-4">
            <Metric label="Progress" value={`${roadmap.stats.percent}%`} />
            <Metric label="Milestones done" value={`${roadmap.stats.milestonesDone}/${roadmap.stats.milestones}`} />
            <Metric
              label="Overdue"
              value={String(roadmap.stats.overdue)}
              tone={roadmap.stats.overdue ? 'warn' : undefined}
            />
            <Metric
              label="Next deadline"
              value={roadmap.stats.nextDeadline ? new Date(roadmap.stats.nextDeadline).toLocaleDateString() : 'none set'}
            />
          </div>

          <ol className="space-y-5">
            {milestones.map((milestone, index) => (
              <li key={milestone.id} className="p-5 rounded-2xl bg-white/[0.02] border border-white/10 space-y-3">
                <div className="flex items-start gap-3">
                  <span className="text-[10px] w-7 h-7 shrink-0 grid place-items-center rounded-full bg-white/5 border border-white/15 text-white/60">
                    {index + 1}
                  </span>
                  <div className="min-w-0 flex-1">
                    <div className="flex flex-wrap items-center gap-2">
                      <span className="text-sm text-white/90">{milestone.title}</span>
                      {milestone.status === 'done' && (
                        <span className="text-[10px] px-1.5 py-0.5 rounded bg-emerald-500/10 border border-emerald-500/20 text-emerald-300">
                          done
                        </span>
                      )}
                      {milestone.estimate && (
                        <span className="text-[11px] text-white/40 inline-flex items-center gap-1">
                          <Clock className="w-3 h-3" />
                          {milestone.estimate}
                        </span>
                      )}
                    </div>
                    {milestone.detail && <p className="text-xs text-white/55 mt-1 leading-relaxed">{milestone.detail}</p>}
                  </div>
                  <button
                    type="button"
                    disabled={busy}
                    onClick={() => void toggleStep(milestone)}
                    className="text-[11px] px-2.5 py-1 rounded-lg bg-white/5 hover:bg-white/10 border border-white/10 text-white/70 disabled:opacity-40 shrink-0"
                  >
                    {milestone.status === 'done' ? 'Reopen' : 'Mark done'}
                  </button>
                </div>

                <ul className="space-y-2">
                  {tasksOf(milestone.id).map((task) => (
                    <StepRow key={task.id} step={task} busy={busy} onToggle={(s) => void toggleStep(s)} onDelete={(s) => void deleteStep(s)} />
                  ))}
                </ul>

                {openFor === milestone.id ? (
                  <div className="flex flex-col sm:flex-row gap-2">
                    <input
                      aria-label="New step"
                      value={newStep}
                      onChange={(e) => setNewStep(e.target.value)}
                      placeholder="Add a step of your own"
                      className="flex-1 px-3 py-2 rounded-xl bg-white/5 border border-white/15 text-xs text-white placeholder:text-white/35 focus:outline-none focus:border-white/40"
                    />
                    <input
                      aria-label="Deadline"
                      type="date"
                      value={deadline}
                      onChange={(e) => setDeadline(e.target.value)}
                      className="px-3 py-2 rounded-xl bg-white/5 border border-white/15 text-xs text-white focus:outline-none focus:border-white/40"
                    />
                    <button
                      type="button"
                      disabled={busy || newStep.trim().length < 3}
                      onClick={() => void addStep(milestone.id)}
                      className="px-4 py-2 rounded-xl bg-white/10 hover:bg-white/20 border border-white/20 text-xs text-white disabled:opacity-40"
                    >
                      Add
                    </button>
                  </div>
                ) : (
                  <button
                    type="button"
                    onClick={() => {
                      setOpenFor(milestone.id);
                      setNewStep('');
                      setDeadline('');
                    }}
                    className="text-[11px] text-white/50 hover:text-white inline-flex items-center gap-1.5"
                  >
                    <Plus className="w-3 h-3" />
                    <span>Add your own step here</span>
                  </button>
                )}
              </li>
            ))}
          </ol>

          <div className="flex flex-wrap items-center gap-3 pt-2">
            {onOpenAgent && (
              <button
                type="button"
                onClick={onOpenAgent}
                className="px-4 py-2 rounded-xl bg-white/5 hover:bg-white/10 border border-white/15 text-white/80 text-xs inline-flex items-center gap-1.5"
              >
                <Sparkles className="w-3.5 h-3.5" />
                <span>Ask the agent what to do next</span>
              </button>
            )}
            <button
              type="button"
              disabled={busy}
              onClick={() => void api.reportFeedback({ feature: 'roadmap', subject: roadmap.title }).catch(() => undefined)}
              className="text-[11px] text-white/40 hover:text-white inline-flex items-center gap-1.5 disabled:opacity-40"
            >
              <Flag className="w-3 h-3" />
              <span>Report a poor plan</span>
            </button>
          </div>

          {view && view.events.length > 0 && (
            <div className="pt-4">
              <h4 className="text-xs uppercase tracking-wider text-white/45 mb-3">Roadmap history, kept rather than deleted</h4>
              <ul className="space-y-2">
                {view.events.slice(0, 8).map((event) => (
                  <li key={event.id} className="text-xs text-white/55 flex items-start gap-2">
                    <span className="text-[10px] px-1.5 py-0.5 rounded bg-white/5 border border-white/10 text-white/45 shrink-0">
                      {event.kind.replace(/_/g, ' ')}
                    </span>
                    <span>
                      {event.title}
                      {event.detail && <span className="block text-white/40 mt-0.5">{event.detail}</span>}
                    </span>
                  </li>
                ))}
              </ul>
            </div>
          )}
        </div>
      )}

      {view && !roadmap && !plan && view.goal && (
        <div className="mt-8 p-5 rounded-2xl bg-white/[0.02] border border-white/10 text-sm text-white/60">
          You have a goal but no roadmap yet. Generate a plan, read it, and save it if it is right.
        </div>
      )}
    </Shell>
  );
};

function Metric({ label, value, tone }: { label: string; value: string; tone?: 'warn' }) {
  return (
    <div className="p-4 rounded-xl bg-white/[0.02] border border-white/10">
      <div className="text-xs text-white/50">{label}</div>
      <div className={`text-2xl font-semibold mt-1 ${tone === 'warn' ? 'text-amber-300' : 'text-white'}`}>{value}</div>
    </div>
  );
}

function Shell({ children }: { children: React.ReactNode }) {
  return <div className="min-h-screen pt-28 pb-16 px-6 max-w-7xl mx-auto text-white">{children}</div>;
}
