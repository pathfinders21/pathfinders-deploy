import React, { useCallback, useEffect, useState } from 'react';
import {
  AlertTriangle,
  Check,
  Flag,
  Loader2,
  RefreshCw,
  ShieldQuestion,
  Sparkles,
  Target,
  Lightbulb,
} from 'lucide-react';
import { ApiError, api, type Assessment, type AssessmentResponse } from '../lib/api.ts';
import { localAssessment, type LocalAssessmentInput } from '../lib/localAssessment.ts';
import { signInHref, type Session } from '../lib/session.ts';

/**
 * The assessment screen: the ASSESS step of the loop.
 *
 * What it refuses to do, deliberately:
 *  - It never shows a model result as fact. Every finding carries the evidence it rests
 *    on, whether that evidence is described work or the student's own claim, and the
 *    engine that produced the text is named on screen.
 *  - It never hides a failure. A provider error is rendered with its real message and a
 *    retry, and a thin profile is answered with the fields that would unblock it.
 *  - It shows reasoning summaries and evidence, never a private chain of thought.
 */

interface Props {
  session: Session;
}

type FormState = {
  goalText: string;
  skillsHave: string;
  skillsWant: string;
  hoursPerWeek: string;
  projectText: string;
};

const toList = (value: string): string[] =>
  value
    .split(',')
    .map((part) => part.trim())
    .filter(Boolean)
    .slice(0, 24);

function EngineBadge({ engine, local = false }: { engine: 'gemini' | 'demo'; local?: boolean }) {
  return engine === 'gemini' ? (
    <span className="text-[10px] px-2 py-0.5 rounded-full border bg-emerald-500/10 text-emerald-300 border-emerald-500/20">
      Generated by the model
    </span>
  ) : (
    <span className="text-[10px] px-2 py-0.5 rounded-full border bg-amber-500/10 text-amber-200 border-amber-500/20">
      {local ? 'Demo engine: computed in your browser' : 'Demo engine: no provider key configured'}
    </span>
  );
}

function FindingCard({ label, tone, children }: { label: string; tone: string; children: React.ReactNode }) {
  return (
    <div className="p-4 rounded-xl bg-white/[0.02] border border-white/10 space-y-2">
      <span className={`text-[10px] px-2 py-0.5 rounded border ${tone}`}>{label}</span>
      {children}
    </div>
  );
}

export const AssessmentPanel: React.FC<Props> = ({ session }) => {
  const [data, setData] = useState<AssessmentResponse | null>(null);
  const [loading, setLoading] = useState(false);
  const [loadError, setLoadError] = useState<ApiError | null>(null);
  const [runError, setRunError] = useState<ApiError | null>(null);
  const [reported, setReported] = useState<string | null>(null);
  const [form, setForm] = useState<FormState>({
    goalText: '',
    skillsHave: '',
    skillsWant: '',
    hoursPerWeek: '',
    projectText: '',
  });

  const ready = session.status === 'ready';
  // No server to ask. The published build is a static site and this preview has no Worker
  // running, so `/api/assessment` cannot answer at all. The screen still works: the same
  // deterministic demo engine the server falls back to runs here instead, labelled as the
  // demo engine and as running in the browser, and nothing is saved.
  const offline = session.status === 'error';
  const profileName = session.status === 'ready' ? session.profile.displayName : '';

  // Prefill from the stored profile so the form is an edit of the truth, not a blank page.
  useEffect(() => {
    if (session.status !== 'ready') return;
    const { profile } = session;
    setForm((prev) => ({
      goalText: prev.goalText || profile.goalsText || '',
      skillsHave: prev.skillsHave || profile.skillsHave.join(', '),
      skillsWant: prev.skillsWant || profile.skillsWant.join(', '),
      hoursPerWeek: prev.hoursPerWeek || profile.hoursPerWeek || '',
      projectText: prev.projectText || profile.projectText || '',
    }));
  }, [session]);

  /** The same fields the server reads, taken from the form the person can actually fill in. */
  const localInput = (): LocalAssessmentInput => ({
    goalText: form.goalText,
    skillsHave: toList(form.skillsHave),
    skillsWant: toList(form.skillsWant),
    hoursPerWeek: form.hoursPerWeek,
    projectText: form.projectText,
  });

  const load = useCallback(async () => {
    if (offline) {
      // With no server there is no stored history to read; the form is the whole input.
      setData({ ok: true, needsMoreInfo: false, assessment: null, history: [] });
      setLoadError(null);
      return;
    }
    if (!ready) return;
    setLoading(true);
    setLoadError(null);
    try {
      setData(await api.assessment());
    } catch (error) {
      setLoadError(
        error instanceof ApiError ? error : new ApiError({ kind: 'server', status: 0, message: 'Could not load your assessment.' }),
      );
    } finally {
      setLoading(false);
    }
  }, [ready, offline]);

  useEffect(() => {
    void load();
  }, [load]);

  const run = async (refresh: boolean) => {
    setLoading(true);
    setRunError(null);
    setReported(null);
    try {
      const result = offline
        ? localAssessment(localInput())
        : await api.runAssessment({
            refresh,
            goalText: form.goalText,
            projectText: form.projectText,
          });
      setData(result);
    } catch (error) {
      setRunError(
        error instanceof ApiError ? error : new ApiError({ kind: 'server', status: 0, message: 'The analysis could not be produced.' }),
      );
    } finally {
      setLoading(false);
    }
  };

  const report = async (feature: 'assessment', subject: string) => {
    try {
      await api.reportFeedback({ feature, subject });
      setReported(subject);
    } catch (error) {
      setRunError(
        error instanceof ApiError ? error : new ApiError({ kind: 'server', status: 0, message: 'That report could not be recorded.' }),
      );
    }
  };

  /* ---------------- gates ---------------- */

  if (session.status === 'loading') {
    return (
      <Shell>
        <div className="flex items-center gap-2 text-white/60 text-sm">
          <Loader2 className="w-4 h-4 animate-spin" />
          <span>Checking your session...</span>
        </div>
      </Shell>
    );
  }

  if (session.status === 'signed_out') {
    return (
      <Shell>
        <div className="p-6 rounded-2xl bg-white/[0.02] border border-white/10 space-y-4 max-w-xl">
          <h2 className="text-lg font-medium text-white">Sign in to run an assessment</h2>
          <p className="text-sm text-white/60">
            Analysis and roadmaps are stored against your account and are only readable by you, so this needs a
            session. Nothing is generated from an identity the browser invented.
          </p>
          <a
            href={signInHref('#/assess')}
            className="liquid-glass rounded-full px-6 py-3 text-sm font-medium text-white inline-block hover:scale-[1.02] transition-transform"
          >
            Sign in to continue
          </a>
        </div>
      </Shell>
    );
  }

  const assessment: Assessment | null = data?.assessment ?? null;
  const readiness = data?.readiness;
  const needsMoreInfo = data?.needsMoreInfo ?? false;

  return (
    <Shell>
      {session.status === 'error' && (
        <div className="mb-8 p-5 rounded-2xl bg-amber-950/40 border border-amber-500/30 text-amber-100 text-sm space-y-2">
          <div className="flex items-center gap-2 font-medium">
            <AlertTriangle className="w-4 h-4" />
            <span>The backend is not answering</span>
          </div>
          <p className="text-xs text-amber-100/80">{session.error.userMessage}</p>
          <p className="text-xs text-amber-100/80">
            The analysis below still runs: it uses the same deterministic demo engine the server falls back to when no
            provider key is configured, here in your browser, and it is labelled as such. No model is involved and
            nothing is saved. Reporting a result needs the server.
          </p>
        </div>
      )}

      <div className="flex flex-col md:flex-row md:items-end justify-between gap-4 pb-8 border-b border-white/10">
        <div>
          <div className="flex items-center gap-2 text-xs text-white/50 mb-2">
            <Target className="w-3.5 h-3.5" />
            <span>Assessment</span>
            <span>·</span>
            <span>{profileName || 'Your profile'}</span>
          </div>
          <h1 style={{ fontFamily: "'Instrument Serif', serif" }} className="text-4xl sm:text-5xl text-white font-normal">
            Where you are, honestly
          </h1>
          <p className="text-white/60 text-sm mt-2 max-w-2xl">
            A reading of what you have told us, against the direction you named: what you can already use, what is
            missing, and what to do about it. Every finding shows the evidence it rests on.
          </p>
        </div>
        {assessment && <EngineBadge engine={assessment.engine} local={offline} />}
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-5 gap-8 mt-8">
        {/* ---------------- form ---------------- */}
        <form
          className="lg:col-span-2 space-y-4"
          onSubmit={(e) => {
            e.preventDefault();
            void run(false);
          }}
        >
          <Field label="The direction you are aiming at" hint="Required. In your own words.">
            <textarea
              rows={3}
              required
              value={form.goalText}
              onChange={(e) => setForm({ ...form, goalText: e.target.value })}
              placeholder="e.g. I want to move from frontend work into backend engineering on payments systems"
              className={INPUT}
            />
          </Field>

          <Field label="Things you can already do" hint="Comma separated.">
            <input
              value={form.skillsHave}
              onChange={(e) => setForm({ ...form, skillsHave: e.target.value })}
              placeholder="TypeScript, React, SQL"
              className={INPUT}
            />
          </Field>

          <Field label="Things you want to be able to do" hint="Comma separated.">
            <input
              value={form.skillsWant}
              onChange={(e) => setForm({ ...form, skillsWant: e.target.value })}
              placeholder="Database tuning, Kafka"
              className={INPUT}
            />
          </Field>

          <Field label="Hours a week you can give this" hint="Optional, but it changes how provisional the result is.">
            <input
              value={form.hoursPerWeek}
              onChange={(e) => setForm({ ...form, hoursPerWeek: e.target.value })}
              placeholder="6"
              className={INPUT}
            />
          </Field>

          <Field
            label="Something you have built"
            hint="A description of real work is the only thing that lets a finding be marked as evidenced rather than self reported."
          >
            <textarea
              rows={5}
              value={form.projectText}
              onChange={(e) => setForm({ ...form, projectText: e.target.value })}
              placeholder="What you built, what it does, and what was hard about it."
              className={INPUT}
            />
          </Field>

          <div className="flex items-center gap-3 pt-2">
            <button
              type="submit"
              disabled={loading || !form.goalText.trim()}
              className="liquid-glass rounded-full px-6 py-3 text-sm font-medium text-white disabled:opacity-40 disabled:cursor-not-allowed inline-flex items-center gap-2"
            >
              {loading ? <Loader2 className="w-4 h-4 animate-spin" /> : <Sparkles className="w-4 h-4" />}
              <span>{assessment ? 'Run again' : 'Analyse my gaps'}</span>
            </button>
            {assessment && (
              <button
                type="button"
                onClick={() => void run(true)}
                disabled={loading}
                className="text-xs text-white/60 hover:text-white inline-flex items-center gap-1.5 disabled:opacity-40"
              >
                <RefreshCw className="w-3.5 h-3.5" />
                <span>Regenerate from scratch</span>
              </button>
            )}
          </div>

          <p className="text-[11px] text-white/40 leading-relaxed">
            {offline
              ? 'Nothing here is saved: your answers are read in this browser and the result is gone when you reload. Run this against the API to store an analysis against your account.'
              : 'Your answers are stored on your profile so you can edit them later, and each analysis is kept so you can see what you were told and when. The text you write is treated as material to analyse, never as instructions.'}
          </p>
        </form>

        {/* ---------------- result ---------------- */}
        <div className="lg:col-span-3 space-y-5">
          {loadError && (
            <div className="p-5 rounded-2xl bg-rose-950/40 border border-rose-500/30 text-rose-100 text-sm space-y-3">
              <div className="flex items-center gap-2 font-medium">
                <AlertTriangle className="w-4 h-4" />
                <span>Could not load your assessment</span>
              </div>
              <p className="text-xs text-rose-100/80">{loadError.userMessage}</p>
              <button type="button" onClick={() => void load()} className="text-xs underline underline-offset-4">
                Try again
              </button>
            </div>
          )}

          {runError && (
            <div className="p-5 rounded-2xl bg-rose-950/40 border border-rose-500/30 text-rose-100 text-sm space-y-3">
              <div className="flex items-center gap-2 font-medium">
                <AlertTriangle className="w-4 h-4" />
                <span>That did not work</span>
              </div>
              <p className="text-xs text-rose-100/80">{runError.userMessage}</p>
              <div className="flex items-center gap-3">
                {runError.retryable && (
                  <button
                    type="button"
                    onClick={() => void run(false)}
                    className="text-xs px-3 py-1.5 rounded-full bg-white/10 hover:bg-white/20"
                  >
                    Retry
                  </button>
                )}
                <span className="text-[11px] text-rose-100/60">
                  {runError.retryable ? 'Nothing was saved.' : 'Nothing was saved, and retrying the identical request would fail the same way.'}
                </span>
              </div>
            </div>
          )}

          {reported && (
            <div className="p-4 rounded-2xl bg-emerald-950/30 border border-emerald-500/25 text-emerald-100 text-xs flex items-start gap-2">
              <Check className="w-4 h-4 shrink-0 mt-0.5" />
              <span>
                Thanks. &ldquo;{reported}&rdquo; was recorded for a human to look at. Nothing about your profile has
                changed.
              </span>
            </div>
          )}

          {loading && !assessment && (
            <div className="p-6 rounded-2xl bg-white/[0.02] border border-white/10 flex items-center gap-3 text-sm text-white/60">
              <Loader2 className="w-4 h-4 animate-spin" />
              <span>Reading your profile...</span>
            </div>
          )}

          {needsMoreInfo && (
            <div className="p-6 rounded-2xl bg-amber-950/30 border border-amber-500/25 space-y-4">
              <div className="flex items-center gap-2 text-amber-100 font-medium text-sm">
                <ShieldQuestion className="w-4 h-4" />
                <span>Not enough to go on yet</span>
              </div>
              <p className="text-xs text-amber-100/80">
                Rather than guess, this asks for the two things an analysis genuinely needs:
              </p>
              <ul className="space-y-1.5">
                {(data?.missing ?? []).map((item) => (
                  <li key={item} className="text-xs text-amber-50 flex items-start gap-2">
                    <span className="w-1 h-1 rounded-full bg-amber-300 mt-1.5 shrink-0" />
                    <span>{item}</span>
                  </li>
                ))}
              </ul>
              {(data?.improvements ?? []).length > 0 && (
                <>
                  <div className="text-[11px] uppercase tracking-wider text-amber-200/70 pt-2">
                    These would make the result better
                  </div>
                  <ul className="space-y-1.5">
                    {(data?.improvements ?? []).map((item) => (
                      <li key={item} className="text-xs text-amber-50/80 flex items-start gap-2">
                        <Lightbulb className="w-3 h-3 mt-0.5 shrink-0" />
                        <span>{item}</span>
                      </li>
                    ))}
                  </ul>
                </>
              )}
            </div>
          )}

          {!needsMoreInfo && !assessment && !loading && (
            <div className="p-6 rounded-2xl bg-white/[0.02] border border-white/10 space-y-3">
              <div className="text-sm text-white/70">No analysis yet.</div>
              <p className="text-xs text-white/50">
                Fill in the direction you are aiming at and run it. Two fields are genuinely required; the rest makes
                the result sharper.
              </p>
              {readiness && readiness.missing.length > 0 && (
                <ul className="space-y-1.5 pt-1">
                  {readiness.missing.map((item) => (
                    <li key={item} className="text-xs text-amber-100/80 flex items-start gap-2">
                      <span className="w-1 h-1 rounded-full bg-amber-300 mt-1.5 shrink-0" />
                      <span>{item}</span>
                    </li>
                  ))}
                </ul>
              )}
            </div>
          )}

          {assessment && (
            <>
              {assessment.provisional && (
                <div className="p-4 rounded-2xl bg-amber-950/30 border border-amber-500/25 text-xs text-amber-100 flex items-start gap-2">
                  <AlertTriangle className="w-4 h-4 shrink-0 mt-0.5" />
                  <span>
                    <strong className="font-medium">Provisional.</strong> You have not described finished work or a
                    weekly time commitment, so the model had less to work with. Treat every finding as a starting
                    question rather than a conclusion.
                  </span>
                </div>
              )}

              {assessment.downgraded > 0 && (
                <div className="p-4 rounded-2xl bg-white/[0.02] border border-white/10 text-xs text-white/70 flex items-start gap-2">
                  <ShieldQuestion className="w-4 h-4 shrink-0 mt-0.5 text-white/50" />
                  <span>
                    {assessment.downgraded} finding{assessment.downgraded === 1 ? ' was' : 's were'} described as
                    evidenced by the model and demoted to self reported, because nothing in your profile shows that
                    skill in use. Add a description of something you have built to change that.
                  </span>
                </div>
              )}

              <div className="p-6 rounded-2xl bg-white/[0.02] border border-white/10 space-y-3">
                <div className="flex items-center justify-between gap-3">
                  <h2 className="text-sm font-medium text-white">Target: {assessment.targetRole}</h2>
                  <span className="text-[10px] text-white/40">
                    {new Date(assessment.createdAt).toLocaleString()}
                    {data?.cached ? ' · reused' : ''}
                  </span>
                </div>
                <p className="text-sm text-white/75 leading-relaxed">{assessment.summary}</p>
                {!offline && (
                  <button
                    type="button"
                    onClick={() => void report('assessment', assessment.targetRole)}
                    className="text-[11px] text-white/50 hover:text-white inline-flex items-center gap-1.5"
                  >
                    <Flag className="w-3 h-3" />
                    <span>Report a poor recommendation</span>
                  </button>
                )}
              </div>

              <div className="space-y-3">
                <h3 className="text-xs uppercase tracking-wider text-white/50">
                  What you can already use ({assessment.strengths.length})
                </h3>
                {assessment.strengths.map((finding) => (
                  <FindingCard
                    key={finding.skill}
                    label={finding.source === 'evidenced' ? 'Evidenced' : 'Self reported'}
                    tone={
                      finding.source === 'evidenced'
                        ? 'bg-emerald-500/10 text-emerald-300 border-emerald-500/20'
                        : 'bg-white/5 text-white/60 border-white/15'
                    }
                  >
                    <div className="text-sm text-white">{finding.skill}</div>
                    <p className="text-xs text-white/60 leading-relaxed">{finding.evidence}</p>
                    <Confidence value={finding.confidence} />
                  </FindingCard>
                ))}
              </div>

              <div className="space-y-3">
                <h3 className="text-xs uppercase tracking-wider text-white/50">
                  What is missing ({assessment.gaps.length})
                </h3>
                {assessment.gaps.map((gap) => (
                  <FindingCard
                    key={gap.skill}
                    label={gap.priority === 'high' ? 'High priority' : gap.priority === 'medium' ? 'Medium' : 'Can wait'}
                    tone={
                      gap.priority === 'high'
                        ? 'bg-rose-500/10 text-rose-300 border-rose-500/20'
                        : gap.priority === 'medium'
                        ? 'bg-amber-500/10 text-amber-200 border-amber-500/20'
                        : 'bg-white/5 text-white/60 border-white/15'
                    }
                  >
                    <div className="text-sm text-white">{gap.skill}</div>
                    <p className="text-xs text-white/70 leading-relaxed">{gap.why}</p>
                    <p className="text-xs text-white/50 leading-relaxed">
                      <span className="text-white/40">Evidence: </span>
                      {gap.evidence}
                    </p>
                    <ul className="space-y-1 pt-1">
                      {gap.exercises.map((exercise) => (
                        <li key={exercise} className="text-xs text-white/70 flex items-start gap-2">
                          <span className="w-1 h-1 rounded-full bg-white/40 mt-1.5 shrink-0" />
                          <span>{exercise}</span>
                        </li>
                      ))}
                    </ul>
                    <Confidence value={gap.confidence} />
                  </FindingCard>
                ))}
              </div>

              {(assessment.assumptions.length > 0 || assessment.questionsToStrengthen.length > 0) && (
                <div className="p-5 rounded-2xl bg-white/[0.02] border border-white/10 space-y-3">
                  {assessment.assumptions.length > 0 && (
                    <div>
                      <div className="text-[11px] uppercase tracking-wider text-white/45 mb-1.5">What this assumes</div>
                      <ul className="space-y-1">
                        {assessment.assumptions.map((item) => (
                          <li key={item} className="text-xs text-white/60">
                            {item}
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}
                  {assessment.questionsToStrengthen.length > 0 && (
                    <div>
                      <div className="text-[11px] uppercase tracking-wider text-white/45 mb-1.5">
                        Answer these and it gets sharper
                      </div>
                      <ul className="space-y-1">
                        {assessment.questionsToStrengthen.map((item) => (
                          <li key={item} className="text-xs text-white/70">
                            {item}
                          </li>
                        ))}
                      </ul>
                    </div>
                  )}
                </div>
              )}

              <p className="text-[11px] text-white/40 leading-relaxed">{data?.note}</p>
            </>
          )}
        </div>
      </div>
    </Shell>
  );
};

const INPUT =
  'w-full px-3.5 py-2.5 rounded-xl bg-white/5 border border-white/10 text-sm text-white placeholder:text-white/30 focus:outline-none focus:border-white/40';

function Field({ label, hint, children }: { label: string; hint?: string; children: React.ReactNode }) {
  return (
    <label className="block space-y-1.5">
      <span className="block text-xs font-medium text-white/70">{label}</span>
      {hint && <span className="block text-[11px] text-white/40">{hint}</span>}
      {children}
    </label>
  );
}

function Confidence({ value }: { value: number }) {
  const pct = Math.round(Math.min(1, Math.max(0, value)) * 100);
  return (
    <div className="flex items-center gap-2 pt-1">
      <div className="w-24 h-1 rounded-full bg-white/10 overflow-hidden">
        <div className="h-full bg-white/50" style={{ width: `${pct}%` }} />
      </div>
      <span className="text-[10px] text-white/40">model confidence {pct}% · not a probability of success</span>
    </div>
  );
}

function Shell({ children }: { children: React.ReactNode }) {
  return <div className="min-h-screen pt-28 pb-16 px-6 max-w-7xl mx-auto text-white">{children}</div>;
}
