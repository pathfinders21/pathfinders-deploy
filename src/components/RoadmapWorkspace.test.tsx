// @vitest-environment jsdom
/**
 * The roadmap screen, driven through its real controls.
 *
 * What these pin is the rule that matters for a judge: a generated plan is a proposal
 * until a person saves it, and generation itself never marks anything complete.
 */
import React from 'react';
import { afterEach, beforeEach, describe, expect, it, vi } from 'vitest';
import { cleanup, fireEvent, render, screen, waitFor } from '@testing-library/react';
import { RoadmapWorkspace } from './RoadmapWorkspace.tsx';
import type { Session } from '../lib/session.ts';

const READY: Session = {
  status: 'ready',
  role: 'mentee',
  roleChosen: true,
  completion: 80,
  onboardingComplete: true,
  isMentor: false,
  profile: {
    userId: 'u1',
    role: 'mentee',
    displayName: 'Avik',
    email: 'a@example.com',
    goalsText: 'Become a backend engineer',
    projectText: '',
    skillsHave: ['TypeScript'],
    skillsWant: ['Kafka'],
    interests: [],
    industries: [],
    hoursPerWeek: '6',
    completion: 80,
  },
};

const GOAL = {
  id: 'g1',
  userId: 'u1',
  title: 'Become a backend engineer',
  rationale: '',
  source: 'user' as const,
  status: 'active' as const,
  createdAt: '2026-10-01T00:00:00.000Z',
  updatedAt: '2026-10-01T00:00:00.000Z',
};

const STEP = {
  id: 's1',
  parentId: null,
  position: 0,
  title: 'Ship a typed API',
  detail: '',
  status: 'pending' as const,
  kind: 'milestone' as const,
  origin: 'ai' as const,
  aiGenerated: true,
  source: 'ai',
  estimate: '2 weeks',
  deadline: null,
  createdAt: '2026-10-01T00:00:00.000Z',
  updatedAt: '2026-10-01T00:00:00.000Z',
  lastTouchedAt: '2026-10-01T00:00:00.000Z',
};

const PLAN = {
  title: 'Backend foundations',
  rationale: 'Sized for 6 hours a week.',
  milestones: [
    { title: 'Data layer', why: 'Payments work is data work.', tasks: [{ title: 'Index a slow query', detail: '', estimate: '2h' }] },
  ],
};

const VIEW = {
  ok: true as const,
  goal: GOAL,
  roadmap: null,
  goals: [GOAL],
  events: [],
};

const VIEW_WITH_ROADMAP = {
  ...VIEW,
  roadmap: {
    id: 'r1',
    goalId: 'g1',
    goalTitle: GOAL.title,
    title: 'Backend foundations',
    rationale: 'Sized for 6 hours a week.',
    status: 'active',
    revision: 1,
    createdAt: '2026-10-01T00:00:00.000Z',
    updatedAt: '2026-10-01T00:00:00.000Z',
    steps: [STEP],
    stats: { total: 2, done: 1, percent: 50, milestones: 1, milestonesDone: 0, overdue: 1, nextDeadline: null },
  },
  events: [{ id: 'e1', kind: 'plan_applied', title: 'Plan saved', detail: '2 steps created', createdAt: '2026-10-02T00:00:00.000Z' }],
};

let routes: Record<string, { status?: number; body: unknown }>;
let calls: Array<{ method: string; path: string; body: unknown }>;

beforeEach(() => {
  calls = [];
  routes = { '/api/roadmap': { body: VIEW } };
  vi.stubGlobal('fetch', async (url: unknown, init?: RequestInit) => {
    const path = String(url);
    calls.push({ method: init?.method ?? 'GET', path, body: init?.body ? JSON.parse(String(init.body)) : undefined });
    const entry = routes[path];
    if (!entry) return new Response(JSON.stringify({ ok: false, error: 'not stubbed' }), { status: 404 });
    return new Response(JSON.stringify(entry.body), {
      status: entry.status ?? 200,
      headers: { 'content-type': 'application/json' },
    });
  });
});

afterEach(() => {
  cleanup();
  vi.unstubAllGlobals();
  vi.restoreAllMocks();
});

const posts = () => calls.filter((c) => c.method === 'POST');

describe('RoadmapWorkspace', () => {
  it('asks for a sign in and fetches nothing without a session', () => {
    render(<RoadmapWorkspace session={{ status: 'signed_out' }} />);
    expect(screen.getByText(/sign in to build a roadmap/i)).toBeTruthy();
    expect(calls).toEqual([]);
  });

  it('treats a generated plan as a proposal and saves nothing until told to', async () => {
    routes['/api/roadmap/plan'] = { body: { ok: true, goal: GOAL, plan: PLAN, engine: 'gemini', requiresConfirmation: true } };
    render(<RoadmapWorkspace session={READY} />);
    await screen.findByText(/Become a backend engineer/);

    fireEvent.click(screen.getByRole('button', { name: /generate a roadmap/i }));
    expect(await screen.findByText(/Proposal, not saved/)).toBeTruthy();
    expect(screen.getByText(/Generated by the model/)).toBeTruthy();
    expect(screen.getByText(/Payments work is data work/)).toBeTruthy();
    expect(screen.getByText(/Index a slow query/)).toBeTruthy();

    // Generation alone wrote nothing: no apply call has happened yet.
    expect(posts().map((c) => c.path)).toEqual(['/api/roadmap/plan']);
  });

  it('saves the plan with an edit applied, then reports what was written', async () => {
    routes['/api/roadmap/plan'] = { body: { ok: true, goal: GOAL, plan: PLAN, engine: 'demo', requiresConfirmation: true } };
    routes['/api/roadmap/apply'] = {
      body: { ...VIEW_WITH_ROADMAP, created: 2, replaced: 0, preserved: 0 },
    };
    render(<RoadmapWorkspace session={READY} />);
    await screen.findByText(/Become a backend engineer/);
    fireEvent.click(screen.getByRole('button', { name: /generate a roadmap/i }));
    await screen.findByText(/Proposal, not saved/);
    expect(screen.getByText(/Demo engine: no provider key configured/)).toBeTruthy();

    fireEvent.change(screen.getByLabelText(/Milestone 1 title/), { target: { value: 'Data layer, revised' } });
    fireEvent.click(screen.getByRole('button', { name: /save this plan to my roadmap/i }));

    await waitFor(() => expect(routes['/api/roadmap/apply']).toBeTruthy());
    const apply = calls.find((c) => c.path === '/api/roadmap/apply');
    expect((apply?.body as { plan: typeof PLAN }).plan.milestones[0].title).toBe('Data layer, revised');
    expect(await screen.findByText(/Saved: 2 new steps/)).toBeTruthy();
    expect(screen.getByText(/starts as not done/i)).toBeTruthy();
  });

  it('shows a provider failure instead of an invented plan', async () => {
    routes['/api/roadmap/plan'] = {
      status: 503,
      body: { ok: false, error: 'No AI provider key is configured.', code: 'ai_unconfigured', requiredEnv: ['AI_API_KEY'] },
    };
    render(<RoadmapWorkspace session={READY} />);
    await screen.findByText(/Become a backend engineer/);

    fireEvent.click(screen.getByRole('button', { name: /generate a roadmap/i }));
    expect(await screen.findByText(/That did not work/i)).toBeTruthy();
    expect(screen.getByText(/AI_API_KEY/)).toBeTruthy();
    expect(screen.queryByText(/Proposal, not saved/)).toBeNull();
  });

  it('counts progress from stored steps and marks a step done through the API', async () => {
    routes['/api/roadmap'] = { body: VIEW_WITH_ROADMAP };
    routes['/api/roadmap/steps/s1'] = { body: { ...VIEW_WITH_ROADMAP, roadmap: { ...VIEW_WITH_ROADMAP.roadmap, stats: { ...VIEW_WITH_ROADMAP.roadmap.stats, done: 2, percent: 100 } } } };
    render(<RoadmapWorkspace session={READY} />);

    expect(await screen.findByText('50%')).toBeTruthy();
    expect(screen.getByText(/1\/2 steps done/)).toBeTruthy();
    expect(screen.getByText(/Ship a typed API/)).toBeTruthy();

    fireEvent.click(screen.getByRole('button', { name: /^mark done$/i }));
    await waitFor(() => expect(calls.some((c) => c.method === 'PATCH' && c.path === '/api/roadmap/steps/s1')).toBe(true));
    expect(await screen.findByText('100%')).toBeTruthy();
  });
});
